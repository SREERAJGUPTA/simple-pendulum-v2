import { createHash } from 'node:crypto';
import { copyFile, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptPath = fileURLToPath(import.meta.url);
const projectRoot = path.resolve(path.dirname(scriptPath), '..');
// .nojekyll is hosting metadata, not a runtime request; some hosts hide it.
const generatedFiles = new Set(['sw.js', 'offline-manifest.json', '.nojekyll']);

async function filesBelow(directory, prefix = '') {
  const items = await readdir(path.join(directory, prefix), { withFileTypes: true });
  const files = [];
  for (const item of items) {
    const relative = path.posix.join(prefix, item.name);
    if (item.isSymbolicLink()) throw new Error(`Cannot precache a symbolic link: ${relative}`);
    if (item.isDirectory()) files.push(...await filesBelow(directory, relative));
    else if (item.isFile() && !generatedFiles.has(relative)) files.push(relative);
  }
  return files.sort();
}

/** Package a completed static release. Does not claim browser/offline validation. */
export async function packageOffline({ root = projectRoot, directory = path.join(root, 'dist') } = {}) {
  await readFile(path.join(directory, 'index.html'));
  await copyFile(path.join(root, 'THIRD_PARTY_NOTICES.md'), path.join(directory, 'third-party-notices.txt'));
  await writeFile(path.join(directory, '.nojekyll'), '');
  const resources = [];
  const releaseHash = createHash('sha256');
  releaseHash.update(await readFile(scriptPath));
  for (const name of await filesBelow(directory)) {
    const bytes = await readFile(path.join(directory, name));
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    const url = `./${name.split('/').map(encodeURIComponent).join('/')}`;
    resources.push({ url, sha256, bytes: bytes.byteLength });
    releaseHash.update(name).update('\0').update(sha256).update('\n');
  }
  const version = releaseHash.digest('hex').slice(0, 20);
  const inventory = {
    application: 'time-in-motion',
    version,
    strategy: 'Complete release precache; activation on first install, closed old clients, or explicit update approval.',
    files: resources.map(({ url, sha256 }) => ({ url, sha256 })),
  };
  const manifestBytes = JSON.stringify(inventory, null, 2) + '\n';
  await writeFile(path.join(directory, 'offline-manifest.json'), manifestBytes);
  resources.push({
    url: './offline-manifest.json',
    sha256: createHash('sha256').update(manifestBytes).digest('hex'),
    bytes: Buffer.byteLength(manifestBytes),
  });

  const worker = `/* Generated by scripts/package-offline.mjs. Do not edit the built worker. */
'use strict';
const VERSION = ${JSON.stringify(version)};
const ASSETS = ${JSON.stringify(resources)};
const SCOPE = self.registration.scope;
const SCOPE_URL = new URL(SCOPE);
const CACHE_PREFIX = 'time-in-motion::' + encodeURIComponent(SCOPE) + '::';
const CACHE_NAME = CACHE_PREFIX + VERSION;
const INDEX_URL = new URL('./index.html', SCOPE).href;
const ASSET_BY_URL = new Map(ASSETS.map(asset => [new URL(asset.url, SCOPE).href, asset]));

function ownedURL(url) {
  return url.origin === SCOPE_URL.origin && url.pathname.startsWith(SCOPE_URL.pathname);
}

// Manifest entries identify one fixed byte representation, checked by SHA-256.
// Use the identical request key for fetch, put, status and match. Module loads
// may add Origin/Accept headers that the precache request did not have; comparing
// those navigation-dependent headers against Vary would miss a valid release.
// This is deliberately limited to exact, owned manifest URLs. It does not ignore
// Vary globally or normalize content-negotiated, external or dynamic requests.
function assetKey(url) {
  return new Request(url, { method: 'GET', mode: 'same-origin', credentials: 'same-origin' });
}

async function checkedResponse(url, asset) {
  const response = await fetch(new Request(assetKey(url), { cache: 'reload' }));
  if (!response.ok || response.type === 'opaque') throw new Error('Offline asset unavailable: ' + url);
  const digest = await crypto.subtle.digest('SHA-256', await response.clone().arrayBuffer());
  const actual = Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, '0')).join('');
  if (actual !== asset.sha256) throw new Error('Offline asset belongs to a different release: ' + url);
  return response;
}

async function completeCache() {
  const cache = await caches.open(CACHE_NAME);
  const present = await Promise.all(Array.from(ASSET_BY_URL.keys(), url => cache.match(assetKey(url))));
  return present.every(Boolean);
}

async function notifyClients(type, extra = {}) {
  const clients = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
  for (const client of clients) {
    if (ownedURL(new URL(client.url))) client.postMessage({ type, version: VERSION, ...extra });
  }
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    const results = await Promise.allSettled(Array.from(ASSET_BY_URL, async ([url, asset]) => {
      const response = await checkedResponse(url, asset);
      await cache.put(assetKey(url), response);
    }));
    if (results.some(result => result.status === 'rejected')) {
      await caches.delete(CACHE_NAME);
      await notifyClients('OFFLINE_CACHE_FAILED');
      throw new Error('Complete release was not cached. Existing active release is preserved.');
    }
    // Do not skipWaiting: a running experiment keeps its current release.
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    if (!await completeCache()) throw new Error('Cannot activate an incomplete offline release.');
    for (const name of await caches.keys()) {
      if (name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME) await caches.delete(name);
    }
    await self.clients.claim();
    await notifyClients('OFFLINE_READY', { complete: true });
  })());
});

self.addEventListener('message', event => {
  if (event.data?.type === 'ACTIVATE_UPDATE') {
    event.waitUntil(self.skipWaiting());
  } else if (event.data?.type === 'GET_CACHE_STATUS') {
    event.waitUntil((async () => {
      const complete = await completeCache();
      const message = { type: 'OFFLINE_CACHE_STATUS', version: VERSION, complete };
      if (event.ports?.[0]) event.ports[0].postMessage(message);
      else event.source?.postMessage(message);
    })());
  }
});

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || !ownedURL(url)) return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      // Serve this release's entry so hashed modules and the page cannot mix.
      const entry = await cache.match(assetKey(INDEX_URL));
      if (entry) return entry;
      try { return await fetch(request); }
      catch { return new Response('The offline copy is unavailable. Reconnect and reload Time in Motion.', { status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' } }); }
    })());
    return;
  }

  const asset = ASSET_BY_URL.get(url.href);
  if (!asset) return; // No external URLs, APIs, or unrelated files are cached.
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(assetKey(url.href));
    if (cached) return cached;
    try {
      const response = await checkedResponse(url.href, asset);
      await cache.put(assetKey(url.href), response.clone());
      return response;
    } catch {
      return new Response('This offline resource is unavailable. Reconnect and reload.', { status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
    }
  })());
});
`;
  await writeFile(path.join(directory, 'sw.js'), worker);
  return { version, files: resources.length, bytes: resources.reduce((sum, resource) => sum + resource.bytes, 0) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  const result = await packageOffline();
  console.log(`Offline release ${result.version}: ${result.files} resources, ${result.bytes} bytes inventoried. Browser lifecycle checks are separate.`);
}
